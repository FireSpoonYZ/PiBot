//! MIME/target classification, origin-marker matching, and bounded text decoding
//! shared by the Linux Wayland and X11 clipboard backends.

pub(crate) const ORIGIN_MARKER_MIME: &str = "application/x-pibot-clipboard-sync";
pub(crate) const ORIGIN_MARKER_VALUE: &[u8] = b"1";

pub(crate) const MIME_TEXT_PLAIN_UTF8: &str = "text/plain;charset=utf-8";
pub(crate) const MIME_TEXT_PLAIN_UTF8_SPACED: &str = "text/plain; charset=utf-8";
pub(crate) const MIME_TEXT_PLAIN: &str = "text/plain";
pub(crate) const MIME_UTF8_STRING: &str = "UTF8_STRING";
pub(crate) const MIME_STRING: &str = "STRING";
pub(crate) const MIME_TEXT: &str = "TEXT";

/// MIME types / X11 targets indicating concealed, transient, or password-manager content.
/// Presence of any of these causes the offer to be skipped without reading payload bytes.
pub(crate) const CONCEALED_MIMES: &[&str] = &[
  "x-kde-passwordManagerHint",
  "ExcludeClipboardContentFromMonitorProcessing",
  "org.nspasteboard.ConcealedType",
  "org.nspasteboard.TransientType",
  "org.nspasteboard.AutoGeneratedType",
  "application/x-password",
  "text/x-password",
];

/// MIME types / X11 targets indicating file-manager copy/cut operations rather than plain text.
pub(crate) const FILE_COPY_MIMES: &[&str] = &[
  "x-special/gnome-copied-files",
  "application/x-kde-cutselection",
];

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum TextEncoding {
  Utf8,
  Iso88591,
}

pub(crate) fn has_origin_marker(mime_types: &[String]) -> bool {
  mime_types
    .iter()
    .any(|m| m.eq_ignore_ascii_case(ORIGIN_MARKER_MIME))
}

pub(crate) fn has_concealed_mime(mime_types: &[String]) -> bool {
  mime_types.iter().any(|offered| {
    CONCEALED_MIMES
      .iter()
      .any(|marker| offered.eq_ignore_ascii_case(marker))
  })
}

pub(crate) fn has_file_copy_mime(mime_types: &[String]) -> bool {
  mime_types.iter().any(|offered| {
    FILE_COPY_MIMES
      .iter()
      .any(|marker| offered.eq_ignore_ascii_case(marker))
  })
}

fn is_utf8_text_plain(mime: &str) -> bool {
  let Some((media, params)) = mime.split_once(';') else {
    return false;
  };
  if !media.trim().eq_ignore_ascii_case(MIME_TEXT_PLAIN) {
    return false;
  }
  params.split(';').any(|param| {
    let Some((key, val)) = param.split_once('=') else {
      return false;
    };
    key.trim().eq_ignore_ascii_case("charset")
      && val.trim().trim_matches('"').eq_ignore_ascii_case("utf-8")
  })
}

/// Selects the highest-priority plain-text MIME type from an advertised list,
/// preserving the exact string advertised by the peer so `offer.receive` matches verbatim.
/// Returns `None` for non-text offers (images, binary payloads, HTML-only, etc.).
pub(crate) fn pick_plain_text_mime(mime_types: &[String]) -> Option<(&str, TextEncoding)> {
  if let Some(m) = mime_types.iter().find(|m| is_utf8_text_plain(m)) {
    return Some((m.as_str(), TextEncoding::Utf8));
  }
  if let Some(m) = mime_types.iter().find(|m| m == MIME_UTF8_STRING) {
    return Some((m.as_str(), TextEncoding::Utf8));
  }
  if let Some(m) = mime_types
    .iter()
    .find(|m| m.trim().eq_ignore_ascii_case(MIME_TEXT_PLAIN))
  {
    return Some((m.as_str(), TextEncoding::Utf8));
  }
  if let Some(m) = mime_types.iter().find(|m| m == MIME_STRING) {
    return Some((m.as_str(), TextEncoding::Iso88591));
  }
  if let Some(m) = mime_types.iter().find(|m| m == MIME_TEXT) {
    return Some((m.as_str(), TextEncoding::Utf8));
  }
  None
}

/// Decodes raw clipboard bytes under a strict byte bound without lossy binary fallback.
pub(crate) fn decode_text_bytes(
  bytes: Vec<u8>,
  encoding: TextEncoding,
  max_bytes: usize,
) -> Option<String> {
  if bytes.len() > max_bytes {
    return None;
  }
  match encoding {
    TextEncoding::Utf8 => {
      let text = String::from_utf8(bytes).ok()?;
      if text.len() > max_bytes {
        return None;
      }
      Some(text)
    }
    TextEncoding::Iso88591 => {
      if let Ok(utf8) = std::str::from_utf8(&bytes) {
        if utf8.len() > max_bytes {
          return None;
        }
        return Some(utf8.to_string());
      }
      if bytes.contains(&0) {
        return None;
      }
      let text: String = bytes.into_iter().map(|b| b as char).collect();
      if text.len() > max_bytes {
        return None;
      }
      Some(text)
    }
  }
}

/// Converts UTF-8 text into ISO-8859-1 bytes for legacy X11 `STRING` target requests.
pub(crate) fn encode_iso88591(text: &str) -> Vec<u8> {
  if text.is_ascii() {
    return text.as_bytes().to_vec();
  }
  text
    .chars()
    .map(|ch| {
      let code = ch as u32;
      if code <= 0xFF {
        code as u8
      } else {
        b'?'
      }
    })
    .collect()
}
